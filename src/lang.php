// Central UI dictionaries + lookup. DB-free (install runs pre-DB).
// Active language: explicit override (install) or global setting.
// Missing key: Hungarian fallback, then the key itself. Never blank.

declare(strict_types=1);

function lang_list(): array
{
    return ['hu' => 'Magyar', 'en' => 'English'];
}

function lang_current(): string
{
    return $GLOBALS['szk_lang'] ?? 'hu';
}

function lang_set(string $lang, bool $force = false): void
{
    // First writer wins (install sets before bootstrap loads);
    // explicit $force overwrites (install choice, tests).
    if (!$force && array_key_exists('szk_lang', $GLOBALS)) {
        return;
    }
    $GLOBALS['szk_lang'] = isset(lang_list()[$lang]) ? $lang : 'hu';
}

function t(string $key, ...$args): string
{
    $lang = lang_current();
    $d = lang_dict($lang);
    if (!array_key_exists($key, $d)) {
        $d = $lang === 'hu' ? [] : lang_dict('hu');
    }
    $s = $d[$key] ?? $key;
    if ($args) {
        $s = vsprintf($s, $args);
    }
    return $s;
}

function lang_dict(string $lang): array
{
    static $all = null;
    if ($all === null) {
        $all = ['hu' => lang_hu(), 'en' => lang_en()];
    }
    return $all[$lang] ?? $all['hu'];
}

